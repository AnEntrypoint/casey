// gui-check-team.mjs -- the areas / bulk team add / feedback / My day / hand-over-to-technician checks of
// scripts/gui-check.mjs, run in the same real headless Chromium against the same scratch store and dashboard.
// Split out only so the main file stays readable; nothing here runs on its own. It seeds its own account,
// areas and reports AFTER every count-sensitive check in the main script, so none of those counts move.
// GUI_CHECK_ONLY=team runs just these.
import path from 'node:path'

export async function runTeamChecks(c) {
  const { check, evalJs, asUser, axeBoth, viewport, sleep, clickText, setField, key, store, base, USER, PW, ids, archive, seenConsole, bodyText, createAccount, SRC } = c
  // The phone touch-target census: every control under 44px in either direction (map excluded).
  const SMALL_JS = `JSON.stringify([...document.querySelectorAll('a[href], button, input:not([type=hidden]):not([type=checkbox]):not([type=radio]), select, textarea, summary, [role=button]')].filter((e) => { const r = e.getBoundingClientRect(); return r.width > 0 && r.height > 0 && !e.closest('.leaflet-container') && !e.classList.contains('app-status-toggle') && (r.height < 43.5 || r.width < 43.5) }).map((e) => e.tagName.toLowerCase() + '.' + String(e.className).split(' ')[0] + ' ' + Math.round(e.getBoundingClientRect().width) + 'x' + Math.round(e.getBoundingClientRect().height) + ' ' + (e.getAttribute('aria-label') || e.innerText || e.name || '').replace(/\\n/g, ' ').slice(0, 24)))`
  const { upsertArea } = await import(path.join(SRC, 'areas.js'))

  console.log('\nareas, bulk add, feedback, my day, hand-over: seeding')
  const r3 = await store.registerContact({ channel: 'whatsapp', external_id: '27845556666', display_name: 'GUI Ranger Three', tier: 'field_worker' })
  await createAccount(store, { username: USER + '-rng3', password: PW, displayName: 'GUI Ranger Three', role: 'eco_ranger', mustChangePassword: false, contactPhone: '084 555 6666' })
  const mkc = async (ext, subject, report, assignee) => {
    const { case: k } = await store.findOrCreateCase({ channel: 'whatsapp', external_id: ext, contact: { name: 'Farmer ' + ext.slice(-3), phone: ext }, subject })
    await store.mergeReport(k.id, report, { id: 'seed', role: 'agent' })
    if (assignee) await store.updateCase(k.id, { assignee }, { id: 'casey-system', role: 'admin' })
    return (await store.getCase(k.id)).id
  }
  const fullRep = { species: 'cattle', symptoms: 'limping', location: 'Musina' }
  ids.W1 = await mkc('27800100001', 'W1 wrong area', { ...fullRep, association: 'Soutpansberg' }, USER + '-rng2')
  ids.W2 = await mkc('27800100002', 'W2 unmapped place', { ...fullRep, location: 'Tshipise', association: 'Tshipise' }, '')
  ids.H1 = await mkc('27800100003', 'H1 complete', { ...fullRep, association: 'Vhembe' }, USER + '-rng3')
  ids.H2 = await mkc('27800100004', 'H2 incomplete', { species: 'goats' }, USER + '-rng3')
  await upsertArea(store, { name: 'Vhembe', primary: 'contact:' + r3.id, backups: [USER + '-rng2'], aliases: ['Musina'] }, 'gui-check')
  await upsertArea(store, { name: 'Soutpansberg', primary: USER + '-rng2', backups: [], aliases: [] }, 'gui-check')

  const pickOpt = (name, textStart) => evalJs(`(() => { const s = document.querySelector('[name=${name}]'); if (!s) return null; const o = [...s.options].find((o) => o.text.startsWith(${JSON.stringify(textStart)})); if (!o) return null; s.value = o.value; s.dispatchEvent(new Event('change', { bubbles: true })); return o.value })()`)
  const dialogText = () => evalJs(`(() => { const d = document.querySelector('[role=dialog]'); return d ? d.innerText.replace(/\\n+/g, ' / ') : 'none' })()`)
  const dialogClick = (txt) => evalJs(`(() => { const b = [...document.querySelectorAll('[role=dialog] button')].find((x) => x.innerText.trim().startsWith(${JSON.stringify(txt)})); if (!b) return false; b.click(); return true })()`)
  const dialogType = (v) => evalJs(`(() => { const i = document.querySelector('[role=dialog] input'); const set = Object.getOwnPropertyDescriptor(Object.getPrototypeOf(i), 'value').set; set.call(i, ${JSON.stringify(v)}); i.dispatchEvent(new Event('input', { bubbles: true })); return 1 })()`)
  const asApi = async (suffix, method, p, body) => {
    const login = await fetch(base + '/api/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: USER + suffix, password: PW }) })
    const cookie = (login.headers.get('set-cookie') || '').split(';')[0]
    const r = await fetch(base + p, { method, headers: { cookie, 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined })
    return { s: r.status, j: await r.json().catch(() => null) }
  }
  const hasBtn = (re) => evalJs(`!![...document.querySelectorAll('button')].find((e) => ${re}.test(e.innerText))`)
  const noSideScroll = () => evalJs('document.documentElement.scrollWidth <= window.innerWidth')

  // ---------------------------------------------------------------- Areas panel
  console.log('\noperator: Areas panel (add, unmapped, wrong-area queue)')
  await viewport('d')
  await asUser('', '#panel=areas', 4000)
  const a0 = await bodyText()
  check(/Vhembe/.test(a0) && /Soutpansberg/.test(a0) && /First ranger: GUI Ranger Three/.test(a0), 'the Areas page lists each area with its first ranger by name (not a key)', (a0.match(/First ranger: [^\n]*/) || [''])[0])
  check(/Tshipise/.test(a0) && /Places nobody has mapped yet/.test(a0), 'places no area covers are listed for mapping')
  check(!/\b(alias(es)?|unmapped|relocate|primary|assignee|payload|json)\b/i.test(a0), 'the Areas page uses no alias / unmapped / relocate / primary / assignee jargon')
  const nav0 = await evalJs(`[...document.querySelectorAll('nav a, aside a')].map((e) => e.innerText.trim())`)
  check(nav0.includes('Areas') && nav0.includes('Feedback'), 'the operator nav offers Areas and Feedback', nav0.filter((t) => /Areas|Feedback/.test(t)).join(' | '))
  await clickText('Add an area'); await sleep(600)
  await setField('[name=area-name]', 'Pafuri')
  const prim = await pickOpt('area-primary', 'GUI Ranger Two')
  await setField('[name=area-aliases]', 'Pafuri Gate, Crooks Corner')
  check(!!prim, 'the first-ranger picker offers the registered team by name', String(prim))
  await axeBoth('Areas: add-an-area form open')
  await clickText('Add area', true); await sleep(1600)
  const areasNow = await asApi('', 'GET', '/api/areas')
  const pafuri = areasNow.j && areasNow.j.areas.find((a) => a.name === 'Pafuri')
  check(!!pafuri && pafuri.aliases.includes('Crooks Corner') && pafuri.primary.key === prim, 'adding an area through the form stores its ranger and other names', pafuri && JSON.stringify([pafuri.primary.key, pafuri.aliases]))
  await pickOpt('map-tshipise', 'Pafuri'); await sleep(300)
  await clickText('Add to this area'); await sleep(1800)
  const unm = await asApi('', 'GET', '/api/areas')
  const pafuri2 = unm.j.areas.find((a) => a.name === 'Pafuri')
  check(pafuri2.aliases.includes('Tshipise') && !unm.j.unmapped.groups.some((g) => /Tshipise/i.test(g.value)), 'one press maps an unmapped place into the chosen area, and it leaves the unmapped list', JSON.stringify(unm.j.unmapped.groups.map((g) => g.value)))
  await clickText('Look for them'); await sleep(3500)
  const wr = await bodyText()
  check(/Move to Vhembe/.test(wr) && /The report says the area is Soutpansberg, but the place \(Musina\) is in Vhembe/.test(wr), 'the wrong-area queue names the report, says why in a sentence, and offers the move', (wr.match(/The report says[^\n]*/) || ['no reason line'])[0])
  await axeBoth('Areas: wrong-area queue populated')
  const refW1 = (await asApi('', 'GET', '/api/cases/' + ids.W1)).j.case.ref
  await clickText('Move to Vhembe'); await sleep(700)
  const mvd = await dialogText()
  check(mvd.includes(refW1) && /Move .* to Vhembe\?/.test(mvd) && /GUI Ranger Three/.test(mvd), 'moving a report asks first, naming the reference, the area and the ranger it goes to', mvd.slice(0, 160))
  await dialogClick('Move ' + refW1); await sleep(2200)
  const w1 = await asApi('', 'GET', '/api/cases/' + ids.W1)
  check(w1.j.case.assignee === 'contact:' + r3.id && JSON.parse(w1.j.case.report).association === 'Vhembe' && !(w1.j.area && w1.j.area.possibly_wrong_area), 'confirming moves the report to the area and to that area\'s ranger, and the wrong-area flag clears', JSON.stringify([w1.j.case.assignee, JSON.parse(w1.j.case.report).association]))
  // Case detail: the area line, and the flag when it is raised.
  await asUser('', '#home=cases&case=' + ids.W1, 3500)
  check(/Area: Vhembe/.test(await bodyText()), 'the operator case page states the report\'s area')
  const flagged = await mkc('27800100005', 'W3 flagged', { ...fullRep, association: 'Soutpansberg' }, USER + '-rng2')
  await asUser('', '#home=cases&case=' + flagged, 3500)
  const fl = await bodyText()
  check(/may be in the wrong area/.test(fl) && /Move it to Vhembe/.test(fl), 'the operator case page flags a report that may be in the wrong area, with the fix beside it')
  await axeBoth('operator case page with the wrong-area flag')
  await viewport('p')
  await asUser('', '#panel=areas', 4000)
  await clickText('Look for them'); await sleep(3000)
  const smallA = JSON.parse(await evalJs(SMALL_JS))
  check(smallA.length === 0 && await noSideScroll(), 'phone: every control on the Areas page is at least 44px and nothing scrolls sideways', smallA.slice(0, 3).join(' ; '))
  await viewport('d')

  // ---------------------------------------------------------------- bulk add
  console.log('\noperator: Add many people at once (Reporters panel)')
  await asUser('', '#panel=contacts', 4000)
  const before = await asApi('', 'GET', '/api/roles/roster')
  const LIST = 'name,phone,role,association,smartphone\nAnna Gui,079 123 4567,Eco Ranger,Vhembe,yes\nJohan Gui,082 555 0101,Eco Ranger,Soutpansberg,no\nBad Row,123,ranger,,yes\nAnna Gui Again,079 123 4567,Eco Ranger,Vhembe,yes'
  await setField('[name=bulk-text]', LIST)
  await clickText('Check the list'); await sleep(1800)
  const pv = await bodyText()
  const afterPreview = await asApi('', 'GET', '/api/roles/roster')
  check(/4 lines checked: 2 to add, 1 with no change, 1 problem/.test(pv) || /4 lines checked: 2 to add/.test(pv), 'the preview counts what would be added and what has a problem', (pv.match(/\d+ lines? checked[^\n]*/) || [''])[0])
  check(/Line 2\. Will be added/.test(pv) && /Line 4\. Cannot be added/.test(pv) && /not a phone number/.test(pv), 'each line of the preview says what will happen and why', (pv.match(/Line 4[^\n]*/) || [''])[0])
  check(afterPreview.j.totals.total === before.j.totals.total, 'checking the list writes nothing', `${before.j.totals.total} -> ${afterPreview.j.totals.total} on the roster`)
  await axeBoth('Reporters: bulk-add preview')
  await clickText('Add 2 people'); await sleep(700)
  const conf2 = await dialogText()
  check(/Add 2 people\?/.test(conf2) && /No message is sent to anyone/.test(conf2), 'adding asks first and says no message is sent', conf2.slice(0, 140))
  await dialogClick('Add 2 people'); await sleep(2800)
  const done = await bodyText()
  const roster = await asApi('', 'GET', '/api/roles/roster')
  check(/Done\. 2 added/.test(done), 'after adding, the page reports what was done', (done.match(/Done\.[^\n]*/) || [''])[0])
  check(roster.j.totals.total === before.j.totals.total + 2 && roster.j.areas.some((r) => r.area === 'Vhembe' && r.total >= 1), 'the people were added and the rollout table groups them by area', JSON.stringify(roster.j.totals))
  const copyBox = await evalJs(`(document.querySelector('[name=bulk-results]') || {}).value`)
  check(/Anna Gui/.test(copyBox || '') && /Added/.test(copyBox || ''), 'the results are in a box that can be copied (no download)', (copyBox || '').replace(/\n/g, ' / ').slice(0, 100))
  const rt = await bodyText()
  check(/How the rollout is going, by area/.test(rt) && /has messaged/i.test(rt) && /first report/i.test(rt), 'the rollout table is on the page with plain column names')
  await axeBoth('Reporters: bulk-add finished, rollout table')
  await viewport('p')
  await asUser('', '#panel=contacts', 4000)
  await setField('[name=bulk-text]', LIST); await clickText('Check the list'); await sleep(1500)
  const smallB = JSON.parse(await evalJs(SMALL_JS))
  check(smallB.length === 0 && await noSideScroll(), 'phone: every control in the bulk-add preview is at least 44px and nothing scrolls sideways', smallB.slice(0, 3).join(' ; '))
  await viewport('d')

  // ---------------------------------------------------------------- feedback
  console.log('\nfeedback: send from a field login, read as staff')
  await asUser('-rng3', '', 4000)
  await clickText('GUI Ranger Three'); await sleep(500)
  const menuItems = await evalJs(`[...document.querySelectorAll('[role=menuitem]')].map((e) => e.innerText.trim())`)
  check(menuItems.includes('Send feedback'), 'a field login\'s account menu offers Send feedback', menuItems.join(' | '))
  await clickText('Send feedback'); await sleep(700)
  check(/Send feedback/.test(await dialogText()), 'Send feedback opens a dialog')
  await dialogClick('Send feedback'); await sleep(300)
  check(/Write a few words first/.test(await dialogText()), 'sending an empty note says so in words')
  await setField('[name=feedback-text]', 'GUI check note: the buttons are easy to hit with gloves on.')
  await axeBoth('feedback dialog open')
  await dialogClick('Send feedback'); await sleep(1500)
  check(/Thank you\. Your note was sent to the team/.test(await dialogText()), 'sending shows a plain confirmation', (await dialogText()).slice(0, 100))
  await key('Escape'); await sleep(300)
  const fbField = await asApi('-rng3', 'GET', '/api/feedback')
  check(fbField.s === 403, 'a field login cannot read the feedback list', String(fbField.s))
  await asUser('', '#panel=feedback', 3800)
  const fbT = await bodyText()
  check(/GUI check note: the buttons are easy to hit with gloves on/.test(fbT) && /By week/.test(fbT) && /By kind of person/.test(fbT) && /Eco Ranger/.test(fbT), 'the staff Feedback page shows the note newest first with counts by week and by kind of person')
  check(/GUI Ranger Three/.test(fbT) && !new RegExp(USER + '-rng3').test(fbT), 'the feedback names the person, not their login')
  await axeBoth('Feedback panel')
  await viewport('p')
  await asUser('-rng3', '', 3500)
  await clickText('GUI Ranger Three'); await sleep(400); await clickText('Send feedback'); await sleep(700)
  const smallF = JSON.parse(await evalJs(SMALL_JS))
  check(smallF.length === 0, 'phone: every control in the feedback dialog is at least 44px', smallF.slice(0, 3).join(' ; '))
  await viewport('d')

  // ---------------------------------------------------------------- my day + hand-over
  console.log('\neco ranger: My day, and Send to technician (reversible)')
  await asUser('-rng3', '', 4500)
  const day = await asApi('-rng3', 'GET', '/api/my-day')
  const ht = await bodyText()
  const tiles = JSON.parse(await evalJs(`JSON.stringify([...document.querySelectorAll('.kpi-card')].map((e) => e.innerText.replace(/\\s+/g, ' ').trim()))`))
  check(/My day: in your area/.test(ht) && /My day: your reports/.test(ht) && /My day: what changed since it began/.test(ht), 'the ranger home has the My day block: area, own reports, what changed')
  check(tiles.includes(day.j.yours.open_now + ' Open now') && tiles.includes(day.j.yours.record_full_not_handed_over + ' Complete, not yet sent'), 'the My day figures are the server\'s figures', tiles.join(' | '))
  check(/what each one still needs/i.test(ht) && /record is full: hand it to the technician|record still needs/.test(ht), 'My day says what each report still needs')
  check(!/\b(record_full|handed_to_desk|by_stage|assignee)\b/.test(ht), 'My day shows no field names')
  await axeBoth('ranger home with My day')
  await viewport('p')
  await asUser('-rng3', '', 4500)
  const smallD = JSON.parse(await evalJs(SMALL_JS))
  check(smallD.length === 0 && await noSideScroll(), 'phone: the ranger home with My day has 44px controls and no sideways scroll', smallD.slice(0, 3).join(' ; '))
  await viewport('d')
  await asUser('-rng3', '#case=' + ids.H2, 3500)
  check(!(await hasBtn('/^Send to technician/')), 'an incomplete report does not offer Send to technician')
  await asUser('-rng3', '#case=' + ids.H1, 3500)
  const refH1 = (await asApi('-rng3', 'GET', '/api/cases/' + ids.H1)).j.case.ref
  check(await hasBtn('/^Send to technician/'), 'a complete report offers Send to technician')
  await clickText('Send to technician'); await sleep(700)
  const hd2 = await dialogText()
  check(hd2.includes(refH1) && /ready to sign off/.test(hd2) && /send it back to you/.test(hd2), 'the confirmation names the reference and says the technician can send it back', hd2.slice(0, 170))
  await axeBoth('ranger: send-to-technician confirmation')
  await dialogType('Cow is limping badly')
  await dialogClick('Send ' + refH1); await sleep(2500)
  const sent = await bodyText()
  const h1 = await asApi('-rng3', 'GET', '/api/cases/' + ids.H1)
  check(/Sent to the technician for sign-off/.test(sent) && !(await hasBtn('/^Send to technician/')), 'after sending, the button is gone and the page says it is with the technician')
  check(String(h1.j.case.tags).includes('handed-off') && (h1.j.events || []).some((e) => /HANDED TO THE SIGN-OFF DESK/.test(e.text) && /Cow is limping badly/.test(e.text)), 'the hand-over is on the report with the ranger\'s note', String(h1.j.case.tags))
  await axeBoth('ranger report after sending to the technician')
  await asUser('-aht', '', 4500)
  const at = await bodyText()
  check(new RegExp(refH1).test(at) && /Sent by GUI Ranger Three/.test(at), 'the technician\'s home shows the handed-over report "Sent by <ranger name>"', (at.match(/Sent by [^\n]*/) || ['none'])[0])
  check(/The sign-off desk/.test(at), 'the technician home has the sign-off desk figures')
  await axeBoth('technician home with a handed-over report')
  await asUser('-aht', '#case=' + ids.H1, 3500)
  await clickText('Send back to ranger'); await sleep(600)
  await dialogType('Please add the herd size')
  await dialogClick('Send back ' + refH1); await sleep(2200)
  await asUser('-rng3', '#case=' + ids.H1, 3500)
  check(await hasBtn('/^Send to technician/'), 'the hand-over is reversible: once the technician sends it back the ranger can send it again')
  await viewport('p')
  await asUser('-rng3', '#case=' + ids.H1, 3500)
  const smallH = JSON.parse(await evalJs(SMALL_JS))
  check(smallH.length === 0 && await noSideScroll(), 'phone: a complete report with Send to technician has 44px controls and no sideways scroll', smallH.slice(0, 3).join(' ; '))
  await viewport('d')

  archive()
  const consoleBad = seenConsole.filter((m) => !/status of 404/.test(m) && !/<\/(api\/)?tiles?\//.test(m) && !/<\/api\/ready>/.test(m))
  check(consoleBad.length === 0, 'browser console clean across the new screens', consoleBad[0] || 'no errors or warnings')
}
